"""metadata.json, outside target/: each shipped file's source, date and licence, the files the analysis does not use,
the decision and the deliverables. It names no method and no graded figure."""
import json

import docs
import pack
import world as WL

GEN = "generated by the build's simulator of the road service's instruments and records (no public data)"
LIC = "proprietary, fictional organisation"
F = pack.FILES
WHAT = {
    F["visits"]: ("the station technicians' visit book, rounds and other visits, April 2009 to November 2026", "2026-11-09"),
    F["pw"]: ("the present-weather detectors' ten-minute blocks with precipitation, six stations, 2009 to 2026", "2026-11-09"),
    F["wx"]: ("the detectors' present-weather code list", "2019-03-12"),
    F["radar"]: ("the regional agency's radar cells, 60-minute maxima on one-kilometre pixels, 2013 to 2026", "2026-11-10"),
    F["pixels"]: ("the agency's pixel list with the identifiers used to 2018", "2019-02-27"),
    F["normal"]: ("the agency's 1991 to 2020 precipitation normal on a 500 m grid", "2022-06-14"),
    F["rs_events"]: ("the university programme's weighing gauges in the Rio Scuro valley, events of 2013 to 2026", "2026-11-11"),
    F["rs_gauges"]: ("the university programme's list of its four weighing gauges", "2026-11-11"),
    F["daily"]: ("the agency's daily precipitation series at Ardesa Centro, 1961 to 2026", "2026-11-03"),
    F["traffic"]: ("the SP 141's daily traffic counts by counter, 2019 to 2026", "2026-11-02"),
    docs.FILES["regulation"]: ("the regulation on the protection of gully crossings, revision 4", "2026-11-06"),
    docs.FILES["stations"]: ("the road stations register", "2026-04-20"),
    docs.FILES["crossings"]: ("the gully crossings register with the source areas' survey", "2025-10-08"),
}


def write(path):
    files = {}
    for name, (code, *_rest) in WL.STATIONS.items():
        files[F["tips"] % code] = {"source": GEN, "covers": "the %s logger's tip record, 2009 to 2026" % name,
                                   "pulled": "2026-11-05" if code in ("VFO", "PRD", "RSC", "MSO") else "2026-11-06", "license": LIC}
    for k, (v, d) in WHAT.items():
        files[k] = {"source": GEN, "covers": v, "pulled": d, "license": LIC}
    meta = {"task": "task3", "as_of": "2026-11-13", "organisation": "%s (fictional; the valley and the road are invented)" % docs.ORG,
            "decision": "the protection class of each gully crossing of the SP 141 for the 2027 to 2031 program",
            "deliverables": ["a workbook", "a CSV"],
            "distractor_files": [F["daily"], F["traffic"]],
            "stated_inputs": ["1.0", "3.0", "60 minutes", "6 hours", "1 May to 31 October"],
            "files": files}
    json.dump(meta, open(path, "w"), indent=1, sort_keys=True)
