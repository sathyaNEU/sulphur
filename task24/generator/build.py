def stamps(t, minutes=37):
    u = t.astimezone(dt.timezone.utc).replace(second=0)
    return (u - dt.timedelta(minutes=minutes)).strftime("%Y-%m-%dT%H:%M:%SZ"), u.strftime("%Y-%m-%dT%H:%M:%SZ")


