def _clean(o):
    """figures and effort as plain JSON: numpy scalars to floats, infinities to strings"""
    import numpy as np
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        f = float(o)
        return f if f == f and abs(f) != float("inf") else str(f)
    return o


def build(out):
    tgt = os.path.join(out, "target")
    gdir = os.path.join(out, "golden")
    gen = os.path.join(out, "generator")
    for d in (gdir, gen):
        os.makedirs(d, exist_ok=True)
    make_pack(tgt)
    R = GD.compute(tgt)
    FG = OUT.all_figures(R)
    BANDS = OUT.bands(R, FG)
    SC = OUT.shortcut_figures(R, BANDS)
    EF = OUT.build_effort(R, FG, BANDS)
    json.dump(_clean(dict(FG, bands=BANDS)), open(os.path.join(gen, "figures.json"), "w"), indent=1, sort_keys=True)
    json.dump(_clean(EF), open(os.path.join(gen, "effort.json"), "w"), indent=1)
    wb_t, mm_t = GOLD_FILES["specialist_label_forecast.xlsx"], GOLD_FILES["label_purchase_memo.pdf"]
    OUT.workbook(R["G"], R["B"], R["V"], R["D"], FG, os.path.join(gdir, "specialist_label_forecast.xlsx"),
                 *stamps(wb_t, 44))
    OUT.memo(R["G"], R["B"], R["V"], R["D"], FG, os.path.join(gdir, "label_purchase_memo.pdf"),
             mm_t - dt.timedelta(minutes=16), mm_t)
    PP.own_mtimes(gdir, {})
    PP.zip_folder(tgt, os.path.join(out, "target.zip"), zone="Pacific/Auckland")
    PP.zip_folder(gdir, os.path.join(out, GOLD_ZIP), zone="Pacific/Auckland")
    json.dump(metadata(tgt), open(os.path.join(out, "metadata.json"), "w"), indent=1)
    open(os.path.join(out, "submission.md"), "w").write(WU.submission(FG, BANDS, SC))
    return R, FG, BANDS, EF


def install(out):
    for name in ("target", "golden"):
        dst = os.path.join(TASK, name)
        if os.path.exists(dst):
            shutil.rmtree(dst)
        shutil.copytree(os.path.join(out, name), dst, copy_function=shutil.copy2)
    for name in ("target.zip", GOLD_ZIP, "metadata.json", "submission.md"):
        shutil.copy2(os.path.join(out, name), os.path.join(TASK, name))
    for name in ("figures.json", "effort.json"):
        shutil.copy2(os.path.join(out, "generator", name), os.path.join(HERE, name))


if __name__ == "__main__":
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
        build(out)
        print(out)
    else:
        out = tempfile.mkdtemp()
        build(out)
        install(out)
        print("installed from", out)
