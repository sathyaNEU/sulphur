"""metadata.json, outside target/: each shipped file's source, date, licence and how it was made, the distractors, the
decision and the deliverables. It names no method, no mechanism and no graded figure."""
import json

import docs
import pack

PULL = "2026-11-09"
GEN = "generated by the build's simulator of the organisation's systems (no public data)"
WHAT = {
    "acc": "the app's account export as at 9 November 2026",
    "bill": "the app's billing events, November 2024 to November 2026",
    "attr": "the attribution partner's install export, November 2024 to November 2026",
    "skan": "Apple's install postbacks for the Meta and TikTok iOS campaigns, November 2024 to November 2026",
    "apple": "App Store Connect daily subscription events",
    "google": "Google Play Console daily subscription transactions",
    "spend": "daily ad spend by channel and campaign",
    "creat": "the creative team's ad creative tests",
    "rate": "store ratings by day",
}
DOCS = {"policy": "the growth policy for paid acquisition channels, version 2", "plan": "the 2027 media plan"}


def write(path):
    files = {}
    for k, v in WHAT.items():
        files[pack.FILES[k]] = {"source": GEN, "covers": v, "pulled": PULL, "license": "proprietary, fictional organisation"}
    for k, v in DOCS.items():
        files[docs.FILES[k]] = {"source": GEN, "covers": v, "pulled": PULL, "license": "proprietary, fictional organisation"}
    meta = {"task": "task1", "as_of": "2026-11-10", "organisation": "Zancada Fitness S.L. (fictional)",
            "decision": "the growth policy band of each paid acquisition channel for 2027",
            "deliverables": ["a spreadsheet", "a short note"],
            "distractor_files": [pack.FILES["creat"], pack.FILES["rate"]],
            "files": files}
    json.dump(meta, open(path, "w"), indent=1, sort_keys=True)
