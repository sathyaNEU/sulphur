    for k, name in PK.FILES.items():
        p = os.path.join(target, name)
        files.append(dict(path="target/" + name, describes=ABOUT[k], rows=counts.get(k), source=SOURCE,
                          pulled="2026-11-04", license="CC0-1.0 (generated for this task)", bytes=os.path.getsize(p)))
    return dict(task="task16", as_of="2026-11-04",
                decision="whether a merged health system's enterprise master patient index links patient records "
                         "automatically at its April 2027 conversion, and under which candidate rule, against its "
                         "policy's cap of one false merge per 2,000 automatic links",
                deliverables=["a spreadsheet: each candidate rule's automatic links and false merges, the converted "
                              "index's patients, the Calder Bay records to split and the duplicates left",
                              "a one-page memo with the recommendation"],
                public_inputs=[SURNAMES, FIRSTNAMES],
                distractor_files=["target/" + PK.FILES[k] for k in PK.DISTRACTORS],
                files=files)
