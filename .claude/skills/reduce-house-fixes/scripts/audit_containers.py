class Report:
    def __init__(self):
        self.rows = []      # (level, scope, file, message)
        self.table = []     # per-file facts for the eye

    def add(self, level, scope, f, msg):
        self.rows.append((level, scope, f, msg))

    def fails(self):
        return [r for r in self.rows if r[0] == "FAIL"]


def day(s):
    return s[:10] if s else None


def in_band(d, floor, ceiling):
    return (not floor or d >= floor) and (not ceiling or d <= ceiling)


# ------------------------------------------------------------------------------------------------------- PDF
def pdf_string(v):
    if v is None:
        return ""
    return str(v).strip()


def pdf_date(s):
    m = re.match(r"D:(\d{4})(\d\d)?(\d\d)?(\d\d)?(\d\d)?(\d\d)?", s or "")
    if not m:
        return None
    y, mo, d, h, mi, se = (int(x) if x else 1 if i in (1, 2) else 0 for i, x in enumerate(m.groups()))
    return "%04d-%02d-%02dT%02d:%02d:%02d" % (y, mo, d, h, mi, se)


def audit_pdf(path, rel, rep, floor, ceiling, stamps):
    b = open(path, "rb").read()
    info = {}
    try:
        from pypdf import PdfReader
        r = PdfReader(io.BytesIO(b))
        info = {k: pdf_string(v) for k, v in (r.metadata or {}).items()}
        trailer_id = "/ID" in r.trailer
    except Exception as e:  # a file pypdf cannot read is its own failure
        rep.add("FAIL", "pdf", rel, "pypdf cannot read the file (%s)" % e.__class__.__name__)
        return
    cr, pr = info.get("/Creator", ""), info.get("/Producer", "")
    au, ti, su = info.get("/Author", ""), info.get("/Title", ""), info.get("/Subject", "")
    created, modified = pdf_date(info.get("/CreationDate")), pdf_date(info.get("/ModDate"))
    rep.table.append((rel, "pdf", cr or "-", pr or "-", au or "-", created or "-", modified or "-"))
    for k, v in (("Creator", cr), ("Producer", pr)):
        if not v:
            rep.add("FAIL", "pdf", rel, "%s is empty: a real authoring application always writes it" % k)
        elif GENERATOR.search(v):
            rep.add("FAIL", "pdf", rel, "%s names a generator library: %r" % (k, v[:70]))
    if cr and not GENERATOR.search(cr) and not PDF_CREATOR.match(cr):
        lvl = "FAIL" if ORG_SUFFIX.search(cr) or cr == au else "WARN"
        rep.add(lvl, "pdf", rel, "Creator %r is not an authoring application%s" % (
            cr[:60], " (it is the organisation: a masked generator)" if lvl == "FAIL" else ""))
    if pr and not GENERATOR.search(pr) and not PDF_PRODUCER.match(pr):
        lvl = "FAIL" if ORG_SUFFIX.search(pr) or pr == au else "WARN"
        rep.add(lvl, "pdf", rel, "Producer %r is not a PDF engine%s" % (
            pr[:60], " (it is the organisation: a masked generator)" if lvl == "FAIL" else ""))
    if cr == "LibreOffice Writer":
        rep.add("WARN", "pdf", rel, "LibreOffice writes its module as Creator (Writer), not 'LibreOffice Writer'")
    lo = re.match(r"LibreOffice (\d+\.\d+)", pr or "")
    second = b.split(b"\n", 2)[1] if b.count(b"\n") >= 2 else b""
    if (lo or cr in LO_MODULES) and second != "%äüöß".encode("utf-8"):
        rep.add("FAIL", "pdf", rel, "Creator/Producer claim LibreOffice but the file does not carry LibreOffice's "
                                    "header line: relabelled, not exported")
    if cr in LO_MODULES and not (pr or "").startswith(("LibreOffice", "OpenOffice")):
        rep.add("FAIL", "pdf", rel, "Creator %r is a LibreOffice module but Producer is %r" % (cr, pr[:40]))
    if lo and created:
        rel_date = LO_RELEASE.get(lo.group(1))
        if rel_date and created[:10] < rel_date:
            rep.add("FAIL", "pdf", rel, "Producer LibreOffice %s (released %s) on a document created %s" % (
                lo.group(1), rel_date, created[:10]))
    for tok in (b"ReportLab", b"reportlab", b"FPDF", b"fpdf", b"PyFPDF", b"matplotlib", b"Matplotlib",
                b"cairographics", b"WeasyPrint", b"wkhtmltopdf"):
        if tok in b[:2048] or tok in b[-4096:]:
            rep.add("FAIL", "pdf", rel, "the file carries the generator's banner %r" % tok.decode())
            break
    xmp = re.search(rb"<x:xmpmeta.*?</x:xmpmeta>", b, re.S)
    if xmp:
        for tag in (rb"CreatorTool", rb"Producer"):
            m = re.search(rb"<(?:xmp|pdf):" + tag + rb">([^<]*)<", xmp.group(0)) or \
                re.search(rb"(?:xmp|pdf):" + tag + rb'="([^"]*)"', xmp.group(0))
            if m and GENERATOR.search(m.group(1).decode("utf-8", "ignore")):
                rep.add("FAIL", "pdf", rel, "XMP %s names a generator: %r" % (tag.decode(), m.group(1)[:60]))
    for k in ("/Author", "/Title", "/Subject", "/Keywords"):
        m = GENERATOR.search(info.get(k, ""))
        if m:
            rep.add("FAIL", "pdf", rel, "%s carries %r (the source document's library default)" % (k[1:], m.group(0)))
    if su.strip() == "(unspecified)":
        rep.add("FAIL", "pdf", rel, "Subject is the library's placeholder (unspecified)")
    if not ti:
        rep.add("WARN", "pdf", rel, "no Title: an exported document carries its document title")
    if not au:
        rep.add("WARN", "pdf", rel, "no Author: the issuing person or team belongs in Author")
    if not created:
        rep.add("FAIL", "pdf", rel, "no CreationDate")
    else:
        if not in_band(created[:10], floor, ceiling):
            rep.add("FAIL", "pdf", rel, "CreationDate %s outside the band %s to %s" % (created[:10], floor, ceiling))
        stamps["created"][created].append(rel)
    if modified:
        if created and modified < created:
            rep.add("FAIL", "pdf", rel, "ModDate %s before CreationDate %s" % (modified, created))
        if not in_band(modified[:10], floor, ceiling):
            rep.add("FAIL", "pdf", rel, "ModDate %s outside the band" % modified[:10])
        if modified != created:
            stamps["modified"][modified].append(rel)
    if not trailer_id:
        rep.add("WARN", "pdf", rel, "no file /ID in the trailer: word processors always write one")
    return created


# ------------------------------------------------------------------------------------------------------- OOXML
def xml_field(core, tag):
    m = re.search(r"<%s[^>]*>([^<]*)</%s>" % (tag, tag), core)
    return m.group(1).strip() if m else None


def audit_office(path, rel, rep, floor, ceiling, stamps):
    ext = os.path.splitext(path)[1].lower()
    try:
        z = zipfile.ZipFile(path)
    except zipfile.BadZipFile:
        rep.add("FAIL", ext[1:], rel, "not a readable zip container")
        return
    infos = z.infolist()
    names = [i.filename for i in infos]
    parts = {n: z.read(n) for n in names}
    text = {n: d.decode("utf-8", "ignore") for n, d in parts.items() if n.endswith((".xml", ".rels"))}
    core, app = text.get("docProps/core.xml", ""), text.get("docProps/app.xml", "")
    application = xml_field(app, "Application") or ""
    appver = xml_field(app, "AppVersion") or ""
    creator, last_by = xml_field(core, "dc:creator"), xml_field(core, "cp:lastModifiedBy")
    created, modified = xml_field(core, "dcterms:created"), xml_field(core, "dcterms:modified")
    company = xml_field(app, "Company") or ""
    rep.table.append((rel, ext[1:], application[:34] or "-", company[:28] or "-", creator or "-", created or "-",
                      modified or "-"))
    blob = "\n".join(text.values())
    m = GENERATOR.search(core + "\n" + app)
    if m:
        rep.add("FAIL", ext[1:], rel, "docProps name a generator: %r" % m.group(0))
    for pat, what in TEMPLATE_TELLS:
        if re.search(pat, blob):
            rep.add("FAIL", ext[1:], rel, "the writing library's template survives: %s" % what)
    if "word/stylesWithEffects.xml" in names:
        rep.add("FAIL", ext[1:], rel, "python-docx's template part word/stylesWithEffects.xml (Word 2010) survives")
    if "docProps/thumbnail.jpeg" in names:
        import hashlib
        h = hashlib.sha256(parts["docProps/thumbnail.jpeg"]).hexdigest()[:16]
        if h in LIBRARY_THUMBNAILS:
            rep.add("FAIL", ext[1:], rel, "docProps/thumbnail.jpeg is %s's own template picture, not this file's "
                                          "first page" % LIBRARY_THUMBNAILS[h])
        elif ext == ".docx":
            rep.add("WARN", ext[1:], rel, "Word saves no thumbnail unless asked; this docx carries one")
    excel_like = application == "Microsoft Excel"
    libre = application.startswith("LibreOffice/")
    if not application:
        rep.add("FAIL", ext[1:], rel, "docProps/app.xml has no Application")
    elif application in MAC_TEMPLATE_APPS:
        rep.add("WARN", ext[1:], rel, "Application %r is the library template's; Word and PowerPoint on Windows "
                                      "write Microsoft Office Word / PowerPoint" % application)
    elif not (application in OFFICE_APPS.get(ext, ()) or libre or (ext == ".xlsm" and excel_like)):
        rep.add("FAIL", ext[1:], rel, "Application %r is not an Office application or LibreOffice" % application[:60])
    if application and not re.fullmatch(r"\d+\.\d{4}", appver):
        rep.add("FAIL", ext[1:], rel, "AppVersion %r is not an Office build number (16.0300, 16.0000, 15.0000)" % appver)
    if libre:
        v = re.match(r"LibreOffice/(\d+\.\d+)", application)
        rd = LO_RELEASE.get(v.group(1)) if v else None
        if rd and created and created[:10] < rd and (modified or created)[:10] < rd:
            rep.add("FAIL", ext[1:], rel, "saved by LibreOffice %s (released %s) but last modified %s" % (
                v.group(1), rd, (modified or created)[:10]))
    office_claimed = application in OFFICE_APPS.get(ext, ()) or application in MAC_TEMPLATE_APPS
    if office_claimed:
        if names and names[0] != "[Content_Types].xml":
            rep.add("FAIL", ext[1:], rel, "Office writes [Content_Types].xml first; this file starts with %s" % names[0])
        clocks = {i.date_time for i in infos}
        if clocks != {(1980, 1, 1, 0, 0, 0)}:
            rep.add("FAIL", ext[1:], rel, "Office stamps every entry 1980-01-01; these carry %s (the writing "
                                          "library's clock)" % sorted(clocks)[0][:5].__repr__())
    if libre:
        clocks = sorted({i.date_time for i in infos})
        d0 = "%04d-%02d-%02d" % clocks[0][:3]
        if not in_band(d0, floor, ceiling):
            rep.add("FAIL", ext[1:], rel, "LibreOffice's entry clock %s is outside the band" % d0)
    if ext in (".xlsx", ".xlsm"):
        sheets = [n for n in names if n.startswith("xl/worksheets/") and n.endswith(".xml")]
        inline = sum(text[n].count('t="inlineStr"') for n in sheets)
        shared_refs = sum(len(re.findall(r'<c [^>]*t="s"', text[n])) for n in sheets)
        if inline:
            rep.add("FAIL", "xlsx", rel, "%d inline-string cells: Excel and LibreOffice keep text in sharedStrings.xml" % inline)
        if "xl/sharedStrings.xml" not in names and (inline or shared_refs):
            rep.add("FAIL", "xlsx", rel, "no xl/sharedStrings.xml")
        if "xl/sharedStrings.xml" in names and "sharedStrings" not in text.get("[Content_Types].xml", ""):
            rep.add("FAIL", "xlsx", rel, "sharedStrings.xml is not registered in [Content_Types].xml")
        wb = text.get("xl/workbook.xml", "")
        for pat, what in OPENPYXL_DIALECT:
            if any(re.search(pat, text[n]) for n in [*sheets, "xl/workbook.xml", "xl/styles.xml"] if n in text):
                rep.add("FAIL", "xlsx", rel, "the writing library's dialect: %s" % what)
        if excel_like and '<fileVersion appName="xl"' not in wb:
            rep.add("FAIL", "xlsx", rel, "Excel claimed but workbook.xml has no <fileVersion appName=\"xl\">")
        if libre and '<fileVersion appName="Calc"' not in wb:
            rep.add("FAIL", "xlsx", rel, "LibreOffice claimed but workbook.xml has no <fileVersion appName=\"Calc\">")
        if excel_like and "<TitlesOfParts>" not in app:
            rep.add("WARN", "xlsx", rel, "Excel writes the sheet names into docProps/app.xml TitlesOfParts")
    if ext == ".pptx":
        pres = text.get("ppt/presentation.xml", "")
        sz = re.search(r'<p:sldSz cx="(\d+)" cy="(\d+)"(?: type="([^"]+)")?', pres)
        n_slides = len([x for x in names if re.fullmatch(r"ppt/slides/slide\d+\.xml", x)])
        declared = xml_field(app, "Slides")
        if declared is not None and int(declared) != n_slides:
            rep.add("FAIL", "pptx", rel, "app.xml says %s slides, the deck has %d (the template's counts survive)" % (
                declared, n_slides))
        if sz:
            wide = int(sz.group(1)) * 9 == int(sz.group(2)) * 16
            if wide and sz.group(3) == "screen4x3":
                rep.add("FAIL", "pptx", rel, "a 16:9 slide size typed screen4x3: the 4:3 template's attribute survives")
            pf = xml_field(app, "PresentationFormat") or ""
            if wide and "4:3" in pf:
                rep.add("FAIL", "pptx", rel, "PresentationFormat %r on a 16:9 deck" % pf)
        if "ppt/printerSettings/printerSettings1.bin" in names:
            rep.add("WARN", "pptx", rel, "the Mac template's printer settings part survives")
    for emb in [x for x in names if re.match(r"(ppt|word|xl)/embeddings/[^/]+\.(xlsx|docx|pptx)$", x)]:
        tmpd = tempfile.mkdtemp(prefix="emb-")
        ep = os.path.join(tmpd, os.path.basename(emb))
        open(ep, "wb").write(parts[emb])
        sub = Report()
        audit_office(ep, rel + "!" + emb, sub, floor, ceiling, {"created": defaultdict(list), "modified": defaultdict(list)})
        for r_ in sub.rows:
            rep.add(r_[0], "embed", r_[2], r_[3])
        import shutil
        shutil.rmtree(tmpd, ignore_errors=True)
    if not creator:
        rep.add("FAIL", ext[1:], rel, "docProps/core.xml has no creator")
    if not last_by:
        rep.add("WARN", ext[1:], rel, "docProps/core.xml has no lastModifiedBy")
    for k, v in (("created", created), ("modified", modified)):
        if not v:
            rep.add("FAIL", ext[1:], rel, "docProps/core.xml has no %s stamp" % k)
        elif not re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ", v):
            rep.add("FAIL", ext[1:], rel, "%s stamp %r is not the W3CDTF UTC form Office writes" % (k, v))
        elif not in_band(v[:10], floor, ceiling):
            rep.add("FAIL", ext[1:], rel, "%s %s outside the band %s to %s" % (k, v[:10], floor, ceiling))
    if created and modified:
        if modified < created:
            rep.add("FAIL", ext[1:], rel, "modified %s before created %s" % (modified, created))
        stamps["created"][created].append(rel)
        if modified != created:
            stamps["modified"][modified].append(rel)
    return modified or created


# ------------------------------------------------------------------------------------------------------- images
def audit_image(path, rel, rep, floor, ceiling):
    b = open(path, "rb").read()
    found = []
    if b[:8] == b"\x89PNG\r\n\x1a\n":
        i = 8
        while i + 8 <= len(b):
            n = int.from_bytes(b[i:i + 4], "big")
            kind = b[i + 4:i + 8]
            if kind in (b"tEXt", b"iTXt", b"zTXt"):
                body = b[i + 8:i + 8 + n]
                key, _, val = body.partition(b"\x00")
                found.append((key.decode("latin-1"), val[:200].decode("latin-1", "ignore")))
            i += 12 + n
    else:
        for m in re.finditer(rb"(matplotlib|Matplotlib|Pillow|PIL|plotly|ImageMagick|python)[^\x00]{0,40}", b[:65536]):
            found.append(("EXIF", m.group(0).decode("latin-1")))
    for key, val in found:
        if GENERATOR.search(key + " " + val):
            rep.add("FAIL", "image", rel, "%s chunk names a generator: %r" % (key, val[:60]))
        for d in re.findall(r"(20\d\d-\d\d-\d\d)", val):
            if not in_band(d, floor, ceiling):
                rep.add("FAIL", "image", rel, "%s chunk dated %s, outside the band" % (key, d))
    rep.table.append((rel, "image", ";".join(k for k, _ in found) or "-", "-", "-", "-", "-"))


# ------------------------------------------------------------------------------------------------------- folders
def audit_folder(folder, label, rep, floor, ceiling, spread=True):
    stamps = {"created": defaultdict(list), "modified": defaultdict(list)}
    saved = {}
    authors = Counter()
    n_containers = 0
    for root, _, files in os.walk(folder):
        for fn in sorted(files):
            p = os.path.join(root, fn)
            rel = label + "/" + os.path.relpath(p, folder)
            ext = os.path.splitext(fn)[1].lower()
            if ext == ".pdf":
                saved[os.path.relpath(p, folder)] = audit_pdf(p, rel, rep, floor, ceiling, stamps)
                n_containers += 1
                authors[rep.table[-1][4]] += 1
            elif ext in OFFICE_EXT:
                saved[os.path.relpath(p, folder)] = audit_office(p, rel, rep, floor, ceiling, stamps)
                n_containers += 1
                authors[rep.table[-1][4]] += 1
            elif ext in IMAGE_EXT:
                audit_image(p, rel, rep, floor, ceiling)
    for kind in ("created", "modified"):
        for stamp, files in stamps[kind].items():
            if len(files) > 1:
                rep.add("FAIL", "across", label, "%d files share the %s stamp %s: %s" % (
                    len(files), kind, stamp, ", ".join(f.split("/")[-1] for f in files)))
    if spread and n_containers >= 3:
        top, k = authors.most_common(1)[0]
        if top not in ("-", "") and k * 2 > n_containers:
            rep.add("WARN", "across", label, "one author %r on %d of %d documents: files from different teams or "
                                             "bodies carry their own authors" % (top, k, n_containers))
    return saved


def audit_zip(zpath, label, rep, floor, ceiling, saved):
    try:
        z = zipfile.ZipFile(zpath)
    except (zipfile.BadZipFile, OSError):
        rep.add("FAIL", "zip", label, "unreadable zip")
        return
    files = [i for i in z.infolist() if not i.filename.endswith("/")]
    clocks = Counter(i.date_time for i in files)
    if len(files) >= 3 and len(clocks) == 1:
        rep.add("FAIL", "zip", label, "all %d entries carry one mtime %s: every file from one clock" % (
            len(files), "%04d-%02d-%02d %02d:%02d:%02d" % next(iter(clocks))))
    else:
        for t, k in clocks.items():
            if k > 1:
                same = [i.filename.split("/")[-1] for i in files if i.date_time == t]
                rep.add("FAIL", "zip", label, "%d entries share the mtime %s: %s" % (
                    k, "%04d-%02d-%02d %02d:%02d:%02d" % t, ", ".join(same)))
    for i in files:
        d = "%04d-%02d-%02d" % i.date_time[:3]
        if not in_band(d, floor, ceiling):
            rep.add("FAIL", "zip", label, "%s mtime %s outside the band %s to %s" % (i.filename, d, floor, ceiling))
        key = i.filename.split("/", 1)[1] if i.filename.startswith(("target/",)) else i.filename
        own = saved.get(key) or saved.get(i.filename)
        if own:
            zt = dt.datetime(*i.date_time)
            ot = dt.datetime.fromisoformat(own[:19])
            if zt < ot - dt.timedelta(days=2):
                rep.add("FAIL", "zip", label, "%s zipped %s, days before its own save %s" % (
                    i.filename, zt.isoformat(), own[:19]))
        if re.search(r"(^|/)(__MACOSX|\.DS_Store|Thumbs\.db)", i.filename):
            rep.add("FAIL", "zip", label, "system junk entry %s" % i.filename)


# ------------------------------------------------------------------------------------------------------- task
def task_band(task, asof):
    """The pack's ceiling is the fiction's as-of date; the golden is made after it."""
    if not asof:
        mp = os.path.join(task, "metadata.json")
        if os.path.exists(mp):
            m = json.load(open(mp))
            for k in ("as_of", "asof", "pull_date", "setting"):
                v = m.get(k)
                if isinstance(v, str) and re.match(r"\d{4}-\d\d-\d\d", v):
                    asof = v[:10]
                    break
            if not asof:
                ds = [f.get("date") for f in m.get("files", []) if isinstance(f, dict) and f.get("date")]
                ds = [d for d in ds if re.match(r"\d{4}-\d\d-\d\d", str(d))]
                asof = max(ds)[:10] if ds else None
    return asof


def shift(d, days):
    return (dt.date.fromisoformat(d) + dt.timedelta(days=days)).isoformat()


def golden_zips(task):
    return sorted(os.path.join(task, f) for f in os.listdir(task)
                  if f.endswith(".zip") and f != "target.zip" and "golden" in f.lower())


def audit_task(task, asof=None, floor=None, golden_ceiling=None):
    rep = Report()
    asof = task_band(task, asof)
    if not asof:
        rep.add("WARN", "band", task, "no as-of date (pass --asof or record as_of in metadata.json): stamps unjudged "
                                      "against the setting")
    t_floor = floor or (shift(asof, -365 * 12) if asof else None)
    t_ceiling = shift(asof, 1) if asof else None
    g_floor = shift(asof, -30) if asof else None
    g_ceiling = golden_ceiling or (shift(asof, 240) if asof else None)
    tmp = []
    tdir = os.path.join(task, "target")
    tzip = os.path.join(task, "target.zip")
    if not os.path.isdir(tdir) and os.path.exists(tzip):
        d = tempfile.mkdtemp(prefix="audit-")
        tmp.append(d)
        zipfile.ZipFile(tzip).extractall(d)
        tdir = os.path.join(d, "target") if os.path.isdir(os.path.join(d, "target")) else d
    saved = audit_folder(tdir, "target", rep, t_floor, t_ceiling) if os.path.isdir(tdir) else {}
    if os.path.exists(tzip):
        audit_zip(tzip, "target.zip", rep, t_floor, t_ceiling, saved)
    gdir = os.path.join(task, "golden")
    gz = golden_zips(task)
    if not os.path.isdir(gdir) and gz:
        d = tempfile.mkdtemp(prefix="audit-")
        tmp.append(d)
        zipfile.ZipFile(gz[0]).extractall(d)
        gdir = d
    gsaved = audit_folder(gdir, "golden", rep, g_floor, g_ceiling, spread=False) if os.path.isdir(gdir) else {}
    for z in gz:
        audit_zip(z, os.path.basename(z), rep, g_floor, g_ceiling, gsaved)
    for d in tmp:
        import shutil
        shutil.rmtree(d, ignore_errors=True)
    return rep, (t_floor, t_ceiling, g_floor, g_ceiling)


def print_report(rep, title, band=None):
    print("container audit: %s" % title)
    if band:
        print("  band: pack %s to %s, golden %s to %s" % band)
    if rep.table:
        print("  %-58s %-5s %-34s %-28s %-22s %-20s %s" % ("file", "kind", "application / creator", "company / producer",
                                                            "author", "created", "modified"))
        for r in rep.table:
            print("  %-58s %-5s %-34s %-28s %-22s %-20s %s" % (r[0][:58], r[1], str(r[2])[:34], str(r[3])[:28],
                                                                str(r[4])[:22], str(r[5])[:20], r[6]))
    for lvl in ("FAIL", "WARN"):
        for r in rep.rows:
            if r[0] == lvl:
                print("  %s  %-6s %-50s %s" % (lvl, r[1], r[2][:50], r[3]))
    kinds = {r[1] for r in rep.fails()}
    for k in ("pdf", "xlsx", "docx", "pptx", "image", "across", "zip"):
        if k in kinds:
            print("  fix %-6s %s" % (k, FIX[k]))
    n_f, n_w = len(rep.fails()), sum(1 for r in rep.rows if r[0] == "WARN")
    print("  %s: %d FAIL, %d WARN" % ("FAIL" if n_f else "PASS", n_f, n_w))
    return n_f


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task", nargs="?")
    ap.add_argument("--asof", help="the fiction's as-of date, YYYY-MM-DD (default: metadata.json)")
    ap.add_argument("--floor", help="earliest plausible pack stamp (default: twelve years before the as-of)")
    ap.add_argument("--golden-ceiling", help="latest plausible golden stamp (default: 240 days after the as-of)")
    ap.add_argument("--dir", help="audit one folder instead of a task")
    ap.add_argument("--ceiling")
    ap.add_argument("--all", action="store_true", help="every task folder with a target.zip, summary lines")
    a = ap.parse_args()
    if a.dir:
        rep = Report()
        audit_folder(a.dir, os.path.basename(a.dir.rstrip("/")), rep, a.floor, a.ceiling)
        return 1 if print_report(rep, a.dir) else 0
    if a.all:
        root = os.getcwd()
        bad = 0
        for t in sorted((d for d in os.listdir(root) if re.fullmatch(r"task\d+", d)), key=lambda s: int(s[4:])):
            if not os.path.exists(os.path.join(root, t, "target.zip")) and not os.path.isdir(os.path.join(root, t, "target")):
                continue
            rep, _ = audit_task(os.path.join(root, t))
            fails = rep.fails()
            bad += bool(fails)
            kinds = Counter(r[3].split(":")[0][:48] for r in fails)
            print("%-7s %s %3d FAIL  %s" % (t, "FAIL" if fails else "PASS", len(fails),
                                            "; ".join("%s x%d" % kv for kv in kinds.most_common(4))))
        return 1 if bad else 0
    if not a.task:
        ap.error("give a task folder, --dir or --all")
    rep, band = audit_task(a.task, a.asof, a.floor, a.golden_ceiling)
    return 1 if print_report(rep, a.task, band) else 0


if __name__ == "__main__":
    sys.exit(main())
