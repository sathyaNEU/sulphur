#!/usr/bin/env python3
"""The container ship gate (reduce-house-fixes H1): every file a build ships must look like the application that
supposedly saved it wrote it, at a time the fiction allows, and no two files may share a stamp.

    python3 audit_containers.py taskNN                 target/ (or target.zip), golden/ (or the golden zip), both zips
    python3 audit_containers.py taskNN --asof 2026-11-03
    python3 audit_containers.py --dir <folder> --floor 2020-01-01 --ceiling 2026-11-03
    python3 audit_containers.py --all                  every task folder with a target.zip, one summary line each

Exit 1 on any FAIL. A FAIL is a reviewer's rejection already written: the client's input-file check reads Creator
and Producer, the workbook's string table, docProps and the zip entries, and returns the pack for any of them.

What fails, by format (each check names the library tell it hunts):
  PDF   Creator or Producer empty or missing; a generator library in either, in the XMP or in a header comment
        (FPDF, ReportLab, matplotlib, cairo, pypdf, WeasyPrint, wkhtmltopdf, headless Chrome ...); a Producer that
        is the organisation (a masked generator); a Producer claiming LibreOffice on a file LibreOffice did not
        write; a release newer than the document's own date; no CreationDate; a date outside the band;
        Subject "(unspecified)".
  XLSX  the writing library anywhere (openpyxl, xlsxwriter, pandas); inline strings or no sharedStrings.xml;
        openpyxl's dialect (calcId 124519, fullCalcOnLoad, its sheetPr, baseColWidth 8, empty numFmts);
        an Application that is not Microsoft Excel or LibreOffice, or no AppVersion; Excel claimed but
        [Content_Types].xml not first or zip entries on the build clock rather than 1980-01-01; no creator,
        created or modified; a stamp outside the band; modified before created.
  DOCX  python-docx's template (creator, "generated by", Steve Canny, 2013-12-23, thumbnail, stylesWithEffects);
        Word claimed but entries on the build clock; the same core checks.
  PPTX  python-pptx's template (creator, "generated using", Steve Canny, 2013-01-27, "PowerPoint Presentation");
        the same core and zip checks.
  PNG/JPG a Software chunk or EXIF tag naming a library (matplotlib, Pillow, plotly ...); a date chunk off band.
  Across files: two containers with the same created or modified stamp; two zip entries with the same mtime
        (every file from one export clock); a zip mtime outside the band or days before the file's own save.
"""
