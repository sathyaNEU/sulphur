"""metadata.json for task13, outside target/: the decision, the deliverables, the distractors and each file's
provenance, and nothing of how the answer is reached."""
import os

import common as C

DISTRACTORS = ('corrosion', 'easements')


def metadata(target, counts):
    files = []
    for k, name in sorted(C.FILES.items(), key=lambda kv: kv[1]):
        files.append(dict(file=name, bytes=os.path.getsize(os.path.join(target, name)),
                          saved=C.STAMP[k][1].strftime('%Y-%m-%d'), distractor=k in DISTRACTORS))
    return dict(
        task='task13', architecture=5, as_of='2026-11-12',
        decision='the 69 kV work list for the 2026-27 winter and before summer 2027',
        deliverables=list(C.DELIVERABLES),
        source='generated by task13/generator from a simulated electric cooperative (seeds 51301 to 51303): its 69 kV lines, '
               'substations and structures, the weather and lightning over its territory, member loads, line faults and the '
               'records each system keeps of them (two relay vendors, SCADA, the control room, the outage system), the line '
               'crews\' patrols, washing, vegetation and maintenance work, the test insulators, an environmental roost survey '
               'and an independent solar farm\'s own protection export',
        license='synthetic, no third-party data',
        pull_dates='system extracts saved up to 3 November 2026; documents as filed',
        counts=counts,
        distractor_files=[C.FILES[k] for k in DISTRACTORS],
        files=files,
    )
