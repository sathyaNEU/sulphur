    whole = A.run(None, {'window': 'whole'}, L=L)
    check('SF4 the record since the last inspection is filed, and the whole record names another set',
          'day after the inspection' in terms and whole['ref'] != R['ref'], '%d zones on the whole record' % len(whole['ref']))
    ins = L['ins'].sort_values('start')
    clean_then_failed = 0
    for z, g in ins.groupby('Zone'):
        f = list(g.failed)
        clean_then_failed += sum(1 for a, b in zip(f, f[1:]) if not a and b)
