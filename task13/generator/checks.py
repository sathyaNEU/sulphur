RESULTS = []


def check(name, ok, detail=''):
    RESULTS.append((name, bool(ok), detail))


def text_of(path):
    """readable text of a shipped file through one extractor, with a positive control on the same path"""
    ext = os.path.splitext(path)[1].lower()
    if ext in ('.csv', '.geojson'):
        return open(path, encoding='utf-8', errors='replace').read()
    if ext in ('.xlsx', '.docx'):
        with zipfile.ZipFile(path) as z:
            return '\n'.join(re.sub(r'<[^>]+>', ' ', z.read(n).decode('utf-8', 'ignore')) for n in z.namelist()
                             if n.endswith('.xml'))
    if ext == '.pdf':
        from pypdf import PdfReader
        return '\n'.join(p.extract_text() or '' for p in PdfReader(path).pages)
    return ''


def main():
    T = C.TARGET
    L = A.load(T)
    R = A.run(None, L=L)
    F = json.load(open(os.path.join(C.HERE, 'figures.json')))
    E = json.load(open(os.path.join(C.HERE, 'effort.json')))
    files = sorted(os.listdir(T))

    # ------------------------------------------------------------ input gates
    check('gate: 10 or more usable files', len(files) >= 10, '%d files' % len(files))
    cats = {'csv': 'spreadsheet', 'xlsx': 'spreadsheet', 'docx': 'text', 'pdf': 'text', 'geojson': 'text'}
    used = {cats[f.rsplit('.', 1)[1]] for f in files}
    check('gate: two or more file categories', len(used) >= 2, ', '.join(sorted(used)))
    rows = {f: sum(1 for _ in open(os.path.join(T, f), encoding='utf-8')) - 1 for f in files if f.endswith('.csv')}
    check('gate: a CSV of 20,000 rows or more', max(rows.values()) >= 20000, str(rows))
    big = [f for f, n in rows.items() if n >= 1000]
    check('gate: a second large CSV (10 to 20 printed pages or more)', len(big) >= 2, ', '.join(big))
    for k in C.DISTRACTORS:
        check('gate: distractor %s ships and no golden step reads it' % k, C.FILES[k] in files and
              C.FILES[k] not in open(os.path.join(C.HERE, 'analysis.py')).read())
    bad = [f for f in files if re.search(r'readme|dictionary|notes|manifest|distractor|decoy|answer', f, re.I)]
    check('gate: no file describes the pack or names its role', not bad, ', '.join(bad))
    for f in files:
        t = text_of(os.path.join(T, f))
        check('readable: %s' % f, len(t) > 200, '%d characters' % len(t))
        hits = re.findall(r'\b(golden|synthetic|simulated|generated by|generator|distractor|stump|referral rule '
                          r'should|drift(?:s|ing)? clock|overwrit|memory overflow|event memory)\b', t, re.I)
        check('no pack-making or method word in %s' % f, not hits, ', '.join(sorted(set(hits)))[:120])

    # ------------------------------------------------------------ the terms file the WHAT and nothing of the HOW
    terms = text_of(os.path.join(T, C.FILES['terms']))
    check('terms: positive control (the season definition is readable)', '1 April to 31 October' in terms)
    for w in ('negative binomial', 'Poisson', 'clock', 'drift', 'memory', 'verified', 'regression', 'dispersion',
              'inspection found nothing', 'confirmed sound', 'event number', 'site visit', 'drifts'):
        check('terms name no method or device: %s' % w, w.lower() not in terms.lower())
    proc = text_of(os.path.join(T, C.FILES['procedure']))
    check('procedure: positive control readable', 'once in five dry seasons' in proc)
    for w in ('lightning fault', 'referral', 'rule', 'expect'):
        check('procedure says nothing of the analysis: %s' % w, w.lower() not in proc.lower())

    # ------------------------------------------------------------ realism sweep
    zr = L['zr']
    check('realism: zone names take several shapes', zr['zone'].str.contains('-R').sum() > 50 and
          (~zr['zone'].str.contains('-R')).sum() > 30)
    tot = [R['season_tot'][s] for s in A.SEASONS]
    check('realism: no season total is round', all(abs(x - round(x / 50) * 50) > 0.5 for x in tot), str(tot))
    check('realism: no two seasons share a total', len({round(x) for x in tot}) == 5)
    oms = L['oms']
    check('realism: outage cause codes are a dispatcher mix', oms.cause_code.nunique() >= 6)
    lag = pd.Series(L['dl'].event_no).diff().dropna()
    check('realism: controller event numbers jump where memories overflowed', (lag > 1).sum() > 0)
    check('realism: re-read memories repeat events across downloads',
          L['dl'].duplicated(['recloser', 'event_no']).sum() > 1000)
    people = set(C.PEOPLE.values())
    allt = ' '.join(text_of(os.path.join(T, f)) for f in files if f.endswith(('.docx', '.xlsx', '.pdf')))
    named = {p for p in people if p in allt}
    check('realism: every persona in the documents is drawn', named <= people and len(named) >= 3, ', '.join(sorted(named)))

    # ------------------------------------------------------------ the bar block
    # R1 the field's raw material ships, no result precomputed
    check('R1 raw material: stroke records with time, place and current', {'datetime_utc', 'latitude', 'peak_current_ka'} <=
          set(pd.read_csv(os.path.join(T, C.FILES['strokes']), nrows=3).columns))
    check('R1 raw material: device events with their own stamps', 'controller_time' in pd.read_csv(
        os.path.join(T, C.FILES['downloads']), nrows=3).columns)
    sc_cols = set(pd.read_csv(os.path.join(T, C.FILES['scada']), nrows=3).columns)
    check('R1 no column holds a lightning flag or a zone rate', not ({'lightning', 'cause', 'rate', 'expected'} & sc_cols))
    # R2 each mess item neutral: handled wrongly it moves only what it should
    no_dedupe = A.run(None, {'match_dedupe': False}, L=L)
    check('R2 re-read events: counting repeats moves no referral', no_dedupe['ref'] == R['ref'])
    ic = A.run(None, {'excl_ic': True}, L=L)
    check('R2 weak positive discharges: leaving them in or out moves no referral', ic['ref'] == R['ref'])
    # R3 each result's hurried figure outside its band: the careful pass computed end to end (effort.json)
    eff = {r['id']: r for r in E['results']}
    import importlib.util
    spec = importlib.util.spec_from_file_location('eff', os.path.join(C.TASK, '..', '.claude', 'skills', 'stumping', 'effort.py'))
    G = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(G)
    for rid, r in eff.items():
        g = G.grade(r['passes']['thorough'], r)[0]
        check('R3 %s: the golden pass lands its own band' % rid, g == 'right', g)
    lost = [rid for rid, r in eff.items() if G.grade(r['passes']['careful'], r)[0] != 'right']
    check('R3 the careful but hurried pass loses five or more results', len(lost) >= 5, ', '.join(lost))
    # R4 no plant: no copied block, no decoy document
    s = pd.read_csv(os.path.join(T, C.FILES['scada']))
    blk = s.groupby(s.index // 50).apply(lambda d: tuple(d.event)).value_counts()
    check('R4 no repeated block of events', (blk > 3).sum() == 0)
    # R5 no one thing: each hidden factor's footprint runs beyond the deciding zones
    rl = set(R['radioless'])
    dec_rl = rl & set(R['ref'])
    check('R5 drifting clocks run on every radio-less recloser, not only the referred', len(rl) >= 40 and len(rl) > 3 * max(1, len(dec_rl)),
          '%d radio-less, %d of them referred' % (len(rl), len(dec_rl)))
    gaps = sum(1 for z, w in R['cov'].items() for a0, a1, lost in w if lost > 0)
    gapz = {z for z, w in R['cov'].items() if any(lost > 0 for a0, a1, lost in w)}
    check('R5 overwritten memories on many zones, most of them not referred', len(gapz) >= 10 and len(gapz - set(R['ref'])) >= 0.6 * len(gapz),
          '%d reads lost events on %d zones' % (gaps, len(gapz)))
    # R6 the one-fact test computed: no hint rescues more than a third
    n = len(E['results'])
    worst = max(len(h['rescues']) for h in E['hints'])
    check('R6 the largest single hint rescues a third or fewer', worst <= n / 3.0, '%d of %d' % (worst, n))
    # R7 the rivals: every defensible member of the golden family lands inside every graded band
    fam = {'k by moments': {'kfit': 'moments'}, 'match window -0.4..0.5 s': {'win': (-0.4, 0.5)},
           'match window -1.0..1.2 s': {'win': (-1.0, 1.2)}, 'no transformer density term': {'spec': 'notx'},
           'strokes within 300 m': {'rmax': 0.3}, 'strokes within 500 m': {'rmax': 0.5},
           'weak positive discharges left out': {'excl_ic': True}}
    G2 = G
    for name, o in fam.items():
        rr = A.run(None, o, L=L)
        check('R7 rival %s refers the same zones' % name, rr['ref'] == R['ref'], ', '.join(rr['ref_names']))
        pv = EP.pass_values(rr)
        for rid, r in eff.items():
            if rid == 'R4':
                continue
            g = G2.grade(pv[rid], r)[0]
            check('R7 rival %s: %s inside its band' % (name, rid), g == 'right', '%s %s' % (g, pv[rid]))

    # ------------------------------------------------------------ the semantic fork rows (DESIGN_NOTE.md)
    DF = R['DF']
    oms_l = L['oms'][(L['oms'].cause_code == 'LIGHTNING') & (L['oms'].equipment_type != 'Distribution transformer')]
    oms_n = int((A.season_of(oms_l.t_out.values) == 2026).sum())
    check('SF1 a lightning fault is a matched fault start, not a trip or an OMS code',
          R['season_tot'][2026] > 1.3 * oms_n and 'counted once' in terms, '2026: %.0f faults, %d OMS LIGHTNING' % (
              R['season_tot'][2026], oms_n))
    check('SF2 terms 2(g) files the lightning near a zone as ground strokes within 400 m', 'within 400 m' in terms)
    for rm in (0.3, 0.5, 0.8, 1.0):
        rr = A.run(None, {'rmax': rm, 'rexp': 0.4}, L=L)
        check('SF2 faults matched to strokes within %d m refer the same zones (same call)' % (rm * 1000),
              rr['ref'] == R['ref'], '%d zones' % len(rr['ref']))
    check('SF3 the season is 1 April to 31 October', '1 April to 31 October' in terms and
          list(A.season_of(pd.to_datetime(['2026-03-31', '2026-04-01', '2026-10-31', '2026-11-01']))) == [-1, 2026, 2026, -1])
    whole = A.run(None, {'window': 'whole'}, L=L)
    check('SF4 the record since the last inspection is filed, and the whole record names another set',
          'day after the inspection' in terms and whole['ref'] != R['ref'], '%d zones on the whole record' % len(whole['ref']))
    ins = L['ins'].sort_values('start')
    clean_then_failed = 0
    for z, g in ins.groupby('Zone'):
        f = list(g.failed)
        clean_then_failed += sum(1 for a, b in zip(f, f[1:]) if not a and b)
    nf = A.run(None, {'null': 'not_failed'}, L=L)
    check('SF5 only a later inspection verifies a season: zones inspected clean and found failed at the next round, '
          'and the unverified baseline names another set', clean_then_failed > 0 and nf['ref'] != R['ref'],
          '%d clean-then-failed zones; %d referred on the unverified baseline' % (clean_then_failed, len(nf['ref'])))
    from scipy import stats as SS
    fs = DF[DF.ver & (DF.E > 0)]
    lr = 2 * (SS.nbinom.logpmf(fs.y, R['k'], R['k'] / (R['k'] + fs.E)).sum() - SS.poisson.logpmf(fs.y, fs.E).sum())
    check('SF6 the confirmed-sound seasons reject a Poisson spread', lr > 3.84, '2 dlogL %.2f' % lr)
    check('SF7 the budget is across the network: one in five seasons over every zone', abs(R['alpha'] - 1 / (5.0 * R['N'])) < 1e-12
          and 'Across the network' in terms)
    check('SF8 the rule\'s own sound referrals sit below the budget\'s ceiling', 0.11 <= R['false_per'] <= 0.15 < 0.2,
          '%.3f' % R['false_per'])
    logged = {s: DF.xs(s, level='season').y.sum() for s in A.SEASONS}
    check('SF9 the season totals restore what the memories lost (above the logged count every season)',
          all(R['season_tot'][s] > logged[s] for s in A.SEASONS), str({s: int(v) for s, v in logged.items()}))
    d26 = DF.xs(2026, level='season')
    ref_only = sum(d26.loc[z, 'yf'] - d26.loc[z, 'Ef'] for z in R['ref'])
    pos = float(np.clip(d26.yf - d26.Ef, 0, None).sum())
    b3 = eff['R3']['band']
    check('SF10 terms 2(f) files the quantity; the referred-only and positive-part readings fall outside the band',
          'less the lightning faults its lines would have had' in terms and not (b3[0] <= ref_only <= b3[1]) and
          not (b3[0] <= pos <= b3[1]), 'referred only %.0f, positive parts %.0f, band %s' % (ref_only, pos, b3))
    check('SF11 terms 5 checks each inspection against the rule after the season before it',
          'Each cyclic inspection checks the rule' in terms and len(R['V']) > 100, '%d inspections checked' % len(R['V']))
    X = DF.x.unstack('season')
    scaled = 0.0
    for z in R['ref']:
        W = R['window'](z, 2026)
        ratio = sum(DF.loc[(z, x), 'y'] for x in W) / sum(DF.loc[(z, x), 'E'] for x in W)
        scaled += (ratio - 1) * DF.loc[(z, 2026), 'Ef'] * X.sum().mean() / X[2026].sum()
    b8 = eff['R8']['band']
    check('SF12 2026 scaled to the network\'s average lightning lands inside the avoided-faults band (same call)',
          b8[0] <= scaled <= b8[1], '%.1f in %s' % (scaled, b8))
    pos_e = DF[DF.E > 0]
    check('SF13 restored against the full expectation carries the logged ratio (same call)',
          bool(np.allclose(pos_e.yf * pos_e.E, pos_e.y * pos_e.Ef, rtol=1e-9)))
    rt = A.run(None, {'test': 'restored'}, L=L)
    flip = set(rt['ref']) ^ set(R['ref'])
    check('SF15 testing restored counts as if counted flips only radio-less zones with few recorded faults',
          len(flip) <= 1 and flip <= set(R['radioless']), ', '.join(R['zones'][z] for z in flip))
    # SF16: every covariate set the confirmed seasons support (within 4 AIC of the best) refers the same zones
    import itertools
    from scipy import stats as SS2
    DFr = DF.reset_index()
    vv = DFr[DFr.ver]
    out16 = []
    for rr_ in range(len(R['cols']) + 1):
        for sub in itertools.combinations(R['cols'], rr_):
            cols = list(sub)
            b = A.fit_poisson(vv, cols)
            rate = np.exp(np.c_[np.ones(len(DFr)), DFr[cols].values] @ b)
            fsv = vv.assign(E=rate[vv.index] * vv.xo)
            fsv = fsv[fsv.E > 0]
            k = A.nb_k(fsv.y.values, fsv.E.values)
            aic = 2 * (len(cols) + 2) - 2 * SS2.nbinom.logpmf(fsv.y, k, k / (k + fsv.E)).sum()
            dd = DFr.assign(E=rate * DFr.xo).set_index(['zone_ix', 'season'])
            refz = set()
            for z in range(R['N']):
                W = R['window'](z, 2026)
                yv = int(sum(dd.loc[(z, x), 'y'] for x in W))
                ev = float(sum(dd.loc[(z, x), 'E'] for x in W))
                if W and ev > 0 and A.nb_tail(yv, ev, k) < R['alpha']:
                    refz.add(z)
            out16.append((aic, refz == set(R['ref'])))
    best = min(a_ for a_, _ in out16)
    near = [same for a_, same in out16 if a_ - best < 4]
    worst_diff = min([a_ - best for a_, same in out16 if not same] or [99])
    check('SF16 every covariate set within 4 AIC of the best refers the same zones; any that differs is 5 or more worse',
          all(near) and worst_diff >= 5, '%d sets within 4, nearest differing set %.1f AIC worse' % (len(near), worst_diff))
    gcsv = pd.read_csv(os.path.join(C.GOLDEN, C.DELIVERABLES[0]))
    check('SF14 every zone in the register is scored', len(gcsv) == len(zr) == R['N'], '%d rows' % len(gcsv))

    # ------------------------------------------------------------ the routes: different shortcuts, different wrong sets
    gold = set(R['ref_names'])
    wrong = {tuple(r['answer']) for r in E['routes'] if not r.get('golden') and set(r['answer']) != gold}
    check('routes: three or more distinct wrong referral sets', len(wrong) >= 3, '%d distinct' % len(wrong))

    # ------------------------------------------------------------ figures and bins
    check('figures: the referral set is the golden', F['referred_zones'] == sorted(R['ref_names']))
    for key in ('radioless_2026', 'excess_2026', 'avoided_average_season'):
        check('figures: %s is a whole number off a round value' % key, F[key] % 10 != 0, str(F[key]))
    T26 = R['hist'][2026]
    margin_in = T26[T26.referred].p.max() if T26.referred.any() else 0
    margin_out = T26[~T26.referred].p.min()
    check('gap: the weakest referral and the strongest non-referral sit apart', margin_out / max(margin_in, 1e-300) > 2.0,
          'weakest referred p %.2e, strongest unreferred p %.2e, alpha %.2e' % (margin_in, margin_out, R['alpha']))

    for name, ok, detail in RESULTS:
        print('%-4s %-78s %s' % ('PASS' if ok else 'FAIL', name[:78], detail[:110]))
    fails = [r for r in RESULTS if not r[1]]
    print('%d checks, %d FAIL' % (len(RESULTS), len(fails)))
    return 1 if fails else 0


if __name__ == '__main__':
    sys.exit(main())
