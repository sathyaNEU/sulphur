    check('realism: outage cause codes are a dispatcher mix', oms.cause_code.nunique() >= 6)
    lag = pd.Series(L['dl'].event_no).diff().dropna()
    check('realism: controller event numbers jump where memories overflowed', (lag > 1).sum() > 0)
    check('realism: re-read memories repeat events across downloads',
          L['dl'].duplicated(['recloser', 'event_no']).sum() > 1000)
