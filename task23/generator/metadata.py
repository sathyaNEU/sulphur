"""task23 architecture 1: metadata.json, kept outside the pack: where each file comes from, when it was pulled, and
which files the analysis never needs."""
import os

import params as P

DISTRACTORS = [P.FILES[k] for k in P.DISTRACTORS]
PULLED = {P.FILES[k]: v for k, v in P.PULLED.items()}
PULLED.update({P.FILES["groundwater"]: "2026-10-21", P.FILES["leachate"]: "2026-11-04", P.FILES["sem"]: "2026-10-06",
               P.FILES["odor"]: "2026-11-03"})


def metadata(target, counts, stated=None):
    files = []
    for name in sorted(os.listdir(target)):
        files.append(dict(file=name, bytes=os.path.getsize(os.path.join(target, name)),
                          pulled=PULLED.get(name, "as filed"), distractor=name in DISTRACTORS,
                          rows=counts.get(name)))
    return dict(
        task="task23", architecture=1, as_of=str(P.AS_OF),
        source="generated by task23/generator from a simulated municipal solid waste landfill (seed %d): ten years "
               "of hourly weather with fronts, ridges and the semidiurnal pressure tide at the site's station; waste "
               "placed by cell and material month by month since 1986 and the scale house's tickets since 2021; "
               "methane generated by first-order decay with a six-month lag and the faster decay of the waste the "
               "recirculated leachate reaches; 114 gas wells with their screens, the liquid that rose over them and "
               "the June 2025 pilot pumps; the gas plant's hourly flows; each cover's oxidation as a saturating "
               "capacity with its temperature factor; gas held in the waste as the barometer rises and released as "
               "it falls; the automated chambers, the state's tracer campaigns and the drone flights, each sampling "
               "the hours its own rules allow; and the distractor programs (groundwater, leachate quality, surface "
               "emission monitoring, odor complaints)" % P.SEED,
        license="synthetic, no third-party data",
        pull_dates="extracts pulled November 2 to 4, 2026; workbooks and documents as filed",
        counts=counts, files=files, distractors=DISTRACTORS,
        stated_inputs=stated or [])
