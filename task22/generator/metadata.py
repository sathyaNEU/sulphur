"""task22 architecture 2: metadata.json, kept outside the pack: where each file comes from, when it was pulled, and
which files the analysis never needs."""
import os

import params as P

DISTRACTORS = [P.FILES["cng"], P.FILES["invoices"], P.FILES["workorders"]]
PULLED = {
    P.FILES["reads"]: "2026-11-02", P.FILES["accounts"]: "2026-11-02", P.FILES["register"]: "2026-11-02",
    P.FILES["drs"]: "2026-11-03", P.FILES["gate"]: "2026-11-03", P.FILES["evc"]: "2026-11-03",
    P.FILES["airport"]: "2026-11-04", P.FILES["soil"]: "2026-11-04", P.FILES["cng"]: "2026-11-04",
    P.FILES["workorders"]: "2026-11-05", P.FILES["rebates"]: "2026-11-05",
}


def metadata(target, counts):
    files = []
    for name in sorted(os.listdir(target)):
        files.append(dict(file=name, bytes=os.path.getsize(os.path.join(target, name)),
                          pulled=PULLED.get(name, "as filed"), distractor=name in DISTRACTORS))
    return dict(
        task="task22", architecture=2, as_of="2026-11-05",
        source="generated by task22/generator from a simulated municipal gas distribution system (seed %d): "
               "three winters of weather and the soil under them, fourteen pressure districts with their regulator "
               "stations and correctors (pressure and temperature, and on the EVC-II units the gas's "
               "supercompressibility), about 10,300 premises with their meters (temperature compensated or not, inside "
               "or out), daily use by premise, what each meter registered at its gas temperature, AMR cycle reads and "
               "the billing system's estimates, accounts and vacancies, corrector customers at their delivery "
               "pressures, bypasses and furnace taps, snowbirds, student rentals and dual-fuel heat pumps, leaks, "
               "third-party damage, station heaters, the 2024-25 logger study and the 2024-25 changeout work orders"
               % P.SEED,
        license="synthetic, no third-party data",
        pull_dates="extracts pulled November 2 to 5, 2026; documents as filed",
        counts=counts, files=files, distractors=DISTRACTORS)
