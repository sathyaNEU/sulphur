def metadata(target, counts):
    files = []
    for k, name in PK.FILES.items():
        p = os.path.join(target, name)
        files.append(dict(path="target/" + name, describes=ABOUT[k], rows=counts.get(k),
                          source="synthetic: generated by task22/generator from a simulated municipal electric "
                                 "distribution system (weather, customer loads, network flows, metering and billing "
                                 "systems)", pulled="2026-11-05", license="CC0-1.0 (generated for this task)",
                          bytes=os.path.getsize(p)))
    return dict(task="task22", as_of="2026-11-05",
                decision="the four feeders a city electric utility's 2027 revenue protection sweep covers, and the "
                         "technical losses its 2027 power cost budget carries",
                deliverables=["a spreadsheet: each feeder's monthly energy balance, the line loss bridge, the 2027 "
                              "connections' peak demand and each feeder's 2027 technical losses",
                              "a one-page PDF memo naming the four feeders"],
                distractor_files=["target/" + PK.FILES[k] for k in PK.DISTRACTORS],
                files=files)
