def write(path):
    files = {F[k]: {"source": GEN, "covers": v, "pulled": d, "license": LIC} for k, (v, d) in WHAT.items()}
    assert len(files) == len(F), sorted(set(F.values()) - set(files))
    meta = {"task": "task4", "as_of": "2026-12-02",
            "organisation": "%s (fictional; the brewery, its customers and its suppliers are invented)" % WL.ORG,
            "decision": "the cover for each returnable container fleet for the 2027 summer season: a purchase, a seasonal hire or none",
            "deliverables": ["a workbook", "a deck"],
            "distractor_files": [F["packaging"], F["prices"]],
            "stated_inputs": ["two sevenths", "21 weeks", "the second highest of ten summers", "2017 to 2026",
                              "3,500", "1,500", "1,200", "600"],
            "files": files}
    json.dump(meta, open(path, "w"), indent=1, sort_keys=True)
