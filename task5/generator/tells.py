"""The input-files sweep: every shipped file's text and metadata (email headers and body, PDF text and document
properties, Office XML parts, parquet footers, CSV bytes) read for anything a reviewer of input files could take as an
authoring tell: reserved or documentation domains and addresses, the 555-01 telephone block, placeholder and filler
words, the tools that wrote the files, and words saying how the pack was made."""
import io
import os
import re
import zipfile

PATTERNS = [
    ("a reserved or documentation domain", r"[a-z0-9-]\.(?:example|test|invalid|localhost)\b|\blocalhost\b"),
    ("an example.com, .net or .org address", r"example\.(?:com|net|org)"),
    ("a 555-01xx telephone number", r"(?<![\d.])555[-. ]?01\d\d(?![\d.])"),
    ("a documentation IP block", r"\b(?:192\.0\.2|198\.51\.100|203\.0\.113)\.\d+"),
    ("placeholder text", r"lorem ipsum|\bplaceholder\b|\btodo\b|\btbd\b|xxx+|\bjohn doe\b|\bjane doe\b|\bacme\b|"
                         r"\bfoo\b|\bbar baz\b"),
    ("a word saying how the pack was made", r"\bsynthetic\b|\bsimulated\b|\bfabricated\b|\bdummy\b|\bfake\b|"
                                            r"\bgenerated by\b|\bgenerator\b|\bseed\b|\btask5\b|\bgolden\b|\bdistractor"),
    ("a model or assistant name", r"openai|chatgpt|\bgpt-|\bclaude\b|anthropic|\bllm\b"),
    ("a Python tool in the file", r"\bpandas\b|pyarrow|parquet-cpp|openpyxl|python-docx|reportlab|matplotlib|"
                                  r"xlsxwriter|\bfaker\b|numpy"),
]


def file_text(path):
    b = open(path, "rb").read()
    ext = os.path.splitext(path)[1].lower()
    parts = [] if ext in (".parquet", ".pdf") else [b.decode("utf-8", "ignore")]
    if ext in (".xlsx", ".docx", ".pptx"):
        with zipfile.ZipFile(io.BytesIO(b)) as z:
            # Word's own latent-style list (Placeholder Text and the rest) is in every document it saves: not a tell
            parts += [re.sub(r"<w:lsdException [^>]*/>", "", z.read(n).decode("utf-8", "ignore")) for n in z.namelist()]
    elif ext == ".pdf":
        from pypdf import PdfReader
        r = PdfReader(io.BytesIO(b))
        parts += [p.extract_text() or "" for p in r.pages]
        parts += ["%s %s" % (k, v) for k, v in (r.metadata or {}).items() if k not in ("/Producer", "/Creator")]
    elif ext == ".parquet":
        import pyarrow.parquet as pq
        f = pq.ParquetFile(io.BytesIO(b))
        md = f.metadata
        parts += [str(md.created_by or ""), str(f.schema_arrow.metadata or {}), str(f.schema_arrow)]
        tab = f.read()
        for col in tab.column_names:
            if str(tab.schema.field(col).type) in ("string", "large_string"):
                parts += [str(x) for x in set(tab.column(col).to_pylist())]
    return "\n".join(parts)


def sweep(folder):
    """Every hit as (file, what it is, the text matched); empty when the pack is clean."""
    hits = []
    for f in sorted(os.listdir(folder)):
        t = file_text(os.path.join(folder, f)).lower()
        for what, pat in PATTERNS:
            for m in re.finditer(pat, t):
                hits.append((f, what, m.group(0)))
    return hits


if __name__ == "__main__":
    import sys
    for h in sweep(sys.argv[1]):
        print(h)
